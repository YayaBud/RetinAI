"""
Base dataset class for retinal disease screening datasets.
Supports anomaly CSV generated by generate_anomaly_maps.py

Expected CSV columns:
    image_path
    npy_4ch_path
    amap_path
    label
    split
    anomaly_score
"""

import os
import numpy as np
import pandas as pd
from PIL import Image
import torch
from torch.utils.data import Dataset


class RetinalDataset(Dataset):
    """
    Args:
        labels_file  : Path to anomaly CSV
        transform    : Optional transform (only used if use_4ch=False)
        use_4ch      : If True, loads 4-channel npy tensors
        split        : 'train', 'val', or 'test' (filters CSV)
        label_mapping: Optional dict mapping string labels to ints.
                       If None and labels are strings, raises an error.
                       Subclasses should always pass a fixed mapping so
                       train/val/test instances are always consistent.
    """

    def __init__(self, labels_file, transform=None, use_4ch=True,
                 split=None, label_mapping=None):
        self.transform = transform
        self.use_4ch = use_4ch

        if not os.path.exists(labels_file):
            raise FileNotFoundError(f"Labels file not found: {labels_file}")

        self.labels_df = pd.read_csv(labels_file)

        required_cols = [
            'image_path', 'npy_4ch_path', 'amap_path',
            'label', 'split', 'anomaly_score'
        ]
        missing = [c for c in required_cols if c not in self.labels_df.columns]
        if missing:
            raise ValueError(
                f"CSV missing columns: {missing}. "
                f"Found: {self.labels_df.columns.tolist()}"
            )

        if split is not None:
            self.labels_df = self.labels_df[
                self.labels_df['split'] == split
            ].reset_index(drop=True)

        if len(self.labels_df) == 0:
            raise ValueError(
                f"No samples found{f' for split={split}' if split else ''}"
            )

        # FIX: apply a FIXED label mapping passed in by the subclass.
        # The old auto-mapping inferred the mapping from whatever labels
        # happened to appear in each instance — so if the val subset was
        # missing a class, it got a different mapping than train, causing
        # completely wrong labels during validation.
        if not pd.api.types.is_integer_dtype(self.labels_df['label']):
            if label_mapping is None:
                raise ValueError(
                    f"Labels are strings but no label_mapping was provided. "
                    f"Found labels: {sorted(self.labels_df['label'].unique())}"
                )
            self.labels_df['label'] = self.labels_df['label'].map(label_mapping)

            if self.labels_df['label'].isna().any():
                bad = self.labels_df[self.labels_df['label'].isna()]['label'].unique()
                raise ValueError(
                    f"label_mapping is missing some labels: {bad}. "
                    f"mapping={label_mapping}"
                )

            self.labels_df['label'] = self.labels_df['label'].astype(int)
            print(f"Label mapping applied: {label_mapping}")

    def __len__(self):
        return len(self.labels_df)

    def __getitem__(self, idx):
        row = self.labels_df.iloc[idx]
        label = int(row['label'])

        # ---------- 4-CHANNEL MODE ----------
        if self.use_4ch:
            npy_path = row['npy_4ch_path']
            if not os.path.exists(npy_path):
                raise FileNotFoundError(
                    f"4-channel tensor not found: {npy_path}"
                )
            tensor_4ch = np.load(npy_path)   # [4, H, W]
            image = torch.from_numpy(tensor_4ch).float()
            return image, label

        # ---------- RGB MODE ----------
        image_path = row['image_path']
        if not os.path.exists(image_path):
            raise FileNotFoundError(f"Image file not found: {image_path}")
        image = Image.open(image_path).convert("RGB")
        if self.transform:
            image = self.transform(image)
        return image, label


