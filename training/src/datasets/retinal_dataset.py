class EyePACSDataset(RetinalDataset):
    """5-class Diabetic Retinopathy — labels are already integers 0-4."""

    def __init__(self, labels_file, transform=None, use_4ch=True, split=None):
        # EyePACS labels are integers in CSV — no mapping needed
        super().__init__(labels_file, transform, use_4ch, split,
                         label_mapping=None)

        invalid = self.labels_df[~self.labels_df['label'].isin([0, 1, 2, 3, 4])]
        if len(invalid) > 0:
            raise ValueError(
                f"EyePACS labels must be in [0-4]. "
                f"Found: {invalid['label'].unique()}"
            )


class REFUGEDataset(RetinalDataset):
    """Binary Glaucoma — fixed mapping: non_glaucoma=0, glaucoma=1."""

    # Fixed mapping — never inferred from data so train/val/test always agree
    LABEL_MAPPING = {'non_glaucoma': 0, 'glaucoma': 1}

    def __init__(self, labels_file, transform=None, use_4ch=True, split=None):
        super().__init__(labels_file, transform, use_4ch, split,
                         label_mapping=self.LABEL_MAPPING)

        invalid = self.labels_df[~self.labels_df['label'].isin([0, 1])]
        if len(invalid) > 0:
            raise ValueError(
                f"REFUGE labels must be 0 or 1. "
                f"Found: {invalid['label'].unique()}"
            )


